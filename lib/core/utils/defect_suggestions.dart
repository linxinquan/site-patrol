/// 按缺陷名/描述关键词取整改建议；未命中时返回通用兜底建议。
String suggestionFor(String defectName, [String? desc]) {
  final text = '$defectName ${desc ?? ''}'.toLowerCase();
  for (final r in _rules) {
    for (final k in r.keywords) {
      if (text.contains(k.toLowerCase())) return r.suggestion;
    }
  }
  return _fallback;
}
